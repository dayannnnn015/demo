import { readFileSync, writeFileSync } from 'node:fs';

// Vercel serves public/ from its CDN, so the file is not on the serverless
// function's filesystem. Embed the built shell into the server bundle instead.
// The hashed script and style it references are still served as static assets.
const html = readFileSync('public/index.html', 'utf8');
writeFileSync('src/app-html.ts', `// Generated by scripts/embed-app-page.ts during npm run build. Do not edit.\nexport const appHtml = ${JSON.stringify(html)};\n`);
console.log(`Embedded public/index.html (${html.length} bytes) into src/app-html.ts`);
